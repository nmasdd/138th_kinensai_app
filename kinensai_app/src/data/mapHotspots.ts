export function hotspotsForFloor(floor: string): MapHotspot[] {
  return MAP_HOTSPOTS.filter((h) => h.floor === floor);
}

/**
 * 企画 id に対応するホットスポット (代表・同居のいずれか) を返す。
 * 見つからなければ null (ホットスポットのない企画)。
 */
export function hotspotForExhibitionId(exhibitionId: string): MapHotspot | null {
  return (
    MAP_HOTSPOTS.find((h) => h.id === exhibitionId || h.sharedIds?.includes(exhibitionId)) ?? null
  );
}

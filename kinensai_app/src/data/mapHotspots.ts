/**
 * ベクター校内マップ (VectorMapView) と展示IDを対応付ける定義。
 * 画像は使わない。Googleマップ風のベクター描画が唯一の地図表現。
 *
 * floor は vectorMap.ts の VectorFloor と一致させる。
 * 同一教室に複数企画がある場合 (2F/2F-2、中学1階学習室ほか) は
 * 代表 id のマーカー1件に `sharedIds` で同居企画をぶら下げ、
 * 同一座標への重ね置きを避ける (ずらし配置は誤タップを招くため採用しない)。
 *
 * 対応付け根拠: ベクター部屋名表示と src/data/classCatalog.json の id
 * および src/data/volunteers.ts の place。高校HR教室 (1A〜1J・2A〜2J)
 * は全20教室を登録済み。部活系はベクター上に部屋ブロックとして描画され、
 * place 文字列で一意に特定できるもののみ登録し、講堂・中庭・事務室前・
 * ピロティ・食堂ラベル・視聴覚室 (図上は凡例のみ) などは対象外。
 * 同一教室に複数企画がある場合 (2F/2F-2、中学1階学習室ほか) は
 * 代表 id のマーカー1件に `sharedIds` で同居企画をぶら下げ、
 * 同一座標への重ね置きを避ける (ずらし配置は22pxマーカー同士が
 * 重なって誤タップを招くため採用しない)。
 */

export type MapFloor = '1階' | '2階' | '3階' | '4階 5階';

export interface MapHotspot {
  /** 代表となる Exhibition の id (classCatalog.json / volunteers.ts の id) */
  id: string;
  floor: MapFloor;
  /** ベクター幅に対する 0〜1 の相対 x 座標 */
  x: number;
  /** ベクター高さに対する 0〜1 の相対 y 座標 */
  y: number;
  /**
   * マーカー内に表示する短縮ラベル (未指定なら id を表示)。
   * club-* のような長い id を22pxマーカーに収めるための2〜3文字表記。
   */
  label?: string;
  /** 同一教室に同居する別企画の Exhibition id 一覧 (代表マーカーで共有表示) */
  sharedIds?: string[];
}

